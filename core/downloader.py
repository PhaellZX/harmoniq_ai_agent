import os
import yt_dlp

class AudioDownloader:
    @staticmethod
    def download_audio_from_link(url: str, output_dir: str = "downloads") -> str:
        """
        Downloads audio from a URL supported by yt-dlp and converts it to MP3.
        Returns the absolute file path of the downloaded audio.
        """
        os.makedirs(output_dir, exist_ok=True)

        ydl_opts = {
            'format': 'bestaudio/best',
            'outtmpl': os.path.join(output_dir, '%(title)s.%(ext)s'),
            'postprocessors': [{
                'key': 'FFmpegExtractAudio',
                'preferredcodec': 'mp3',
                'preferredquality': '192',
            }],
            'quiet': True,
            'no_warnings': True,
        }

        try:
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                info = ydl.extract_info(url, download=True)
                filename = ydl.prepare_filename(info)
                
                # Ensures .mp3 extension generated by postprocessor
                base_path, _ = os.path.splitext(filename)
                final_filepath = f"{base_path}.mp3"

                if os.path.exists(final_filepath):
                    return os.path.abspath(final_filepath)
                return os.path.abspath(filename)
        except Exception as e:
            raise RuntimeError(f"Failed to download audio from URL '{url}': {e}")

    # =========================================================================
    # BACKWARD COMPATIBILITY ALIAS
    # =========================================================================
    @staticmethod
    def baixar_audio_por_link(url: str, output_dir: str = "downloads") -> str:
        return AudioDownloader.download_audio_from_link(url=url, output_dir=output_dir)